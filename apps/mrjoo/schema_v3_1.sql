-- MR JOO WORLD v3.1 — شغّله مرة واحدة بعد schema.sql
alter table videos add column if not exists category text default 'general';
create index if not exists videos_cat on videos (category, created_at desc);
create table if not exists convs (id uuid primary key default gen_random_uuid(), title text, is_group boolean default false, dm_key text unique, created_by uuid references profiles(id), created_at timestamptz default now());
create table if not exists conv_members (conv_id uuid references convs(id) on delete cascade, user_id uuid references profiles(id) on delete cascade, primary key (conv_id, user_id));
create index if not exists conv_members_user on conv_members (user_id);
create table if not exists messages (id bigserial primary key, conv_id uuid references convs(id) on delete cascade, user_id uuid references profiles(id) on delete cascade, body text not null, created_at timestamptz default now());
create index if not exists messages_conv on messages (conv_id, id desc);
alter table convs enable row level security;
alter table conv_members enable row level security;
alter table messages enable row level security;


-- MRJOO PRO merged guide: immutable-ish server-side interaction backup.
create table if not exists interactions_backup (
  id bigint generated by default as identity primary key,
  user_id uuid,
  action_type text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists interactions_backup_user_created_idx
  on interactions_backup(user_id, created_at desc);
